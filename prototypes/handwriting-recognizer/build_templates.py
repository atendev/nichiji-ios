"""PROTOTYPE, throwaway. Flattens the bundled KanjiVG stroke SVGs into point lists.

Writes templates.js next to this file: window.TEMPLATES = {"日": [[x,y,x,y,...], ...], ...}
in the KanjiVG 109x109 space, ordered by the index's listIndex.

Run: python3 -I -B prototypes/handwriting-recognizer/build_templates.py
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SVG_DIR = ROOT / "Dataset/AppOnly/stroke-order"
INDEX = ROOT / "Dataset/Shared/kanji-index.json"
OUT = pathlib.Path(__file__).resolve().parent / "templates.js"

TOKEN = re.compile(r"[MmCcSs]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?")
SAMPLES_PER_SEGMENT = 8
STRATIFIED_COUNT = 80
CONFUSABLES = "土士未末人入大犬太王玉千干右石午牛己天夫失矢鳥烏待持特"


def cubic(p0, p1, p2, p3, steps):
    pts = []
    for i in range(1, steps + 1):
        t = i / steps
        u = 1 - t
        pts.append((
            u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
            u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1],
        ))
    return pts


def flatten(d):
    tokens = TOKEN.findall(d)
    i, cmd = 0, None
    cur = (0.0, 0.0)
    last_ctrl = None
    pts = []

    def nums(n):
        nonlocal i
        vals = [float(v) for v in tokens[i:i + n]]
        i += n
        return vals

    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        rel = cmd.islower()
        ox, oy = cur if rel else (0.0, 0.0)
        c = cmd.upper()
        if c == "M":
            x, y = nums(2)
            cur = (ox + x, oy + y)
            pts.append(cur)
            last_ctrl = None
            cmd = "l" if rel else "L"
        elif c == "C":
            x1, y1, x2, y2, x, y = nums(6)
            p1, p2, p3 = (ox + x1, oy + y1), (ox + x2, oy + y2), (ox + x, oy + y)
            pts += cubic(cur, p1, p2, p3, SAMPLES_PER_SEGMENT)
            cur, last_ctrl = p3, p2
        elif c == "S":
            x2, y2, x, y = nums(4)
            p1 = (2 * cur[0] - last_ctrl[0], 2 * cur[1] - last_ctrl[1]) if last_ctrl else cur
            p2, p3 = (ox + x2, oy + y2), (ox + x, oy + y)
            pts += cubic(cur, p1, p2, p3, SAMPLES_PER_SEGMENT)
            cur, last_ctrl = p3, p2
        elif c == "L":
            x, y = nums(2)
            cur = (ox + x, oy + y)
            pts.append(cur)
            last_ctrl = None
        else:
            raise ValueError(f"unhandled command {cmd} in {d}")
    return pts


def main():
    entries = json.loads(INDEX.read_text())["entries"]
    entries.sort(key=lambda e: e["listIndex"])
    templates = {}
    mismatched = []
    for entry in entries:
        char = entry["id"]
        svg = (SVG_DIR / f"{ord(char):05x}.svg").read_text()
        strokes = []
        for d in re.findall(r'<path[^>]* d="([^"]+)"', svg):
            flat = [round(v, 1) for pt in flatten(d) for v in pt]
            strokes.append(flat)
        if len(strokes) != entry["strokeCount"]:
            mismatched.append((char, len(strokes), entry["strokeCount"]))
        templates[char] = strokes
    step = len(entries) / STRATIFIED_COUNT
    stratified = [entries[int(i * step)]["id"] for i in range(STRATIFIED_COUNT)]
    confusables = [c for c in CONFUSABLES if c in templates and c not in stratified]
    targets = stratified + confusables
    OUT.write_text(
        "// PROTOTYPE, generated by build_templates.py. Do not edit.\n"
        "window.TEMPLATES = " + json.dumps(templates, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "window.TEST_TARGETS = " + json.dumps(targets, ensure_ascii=False) + ";\n"
    )
    print(f"{len(targets)} test targets: {len(stratified)} stratified by frequency, {len(confusables)} confusables")
    print(f"{len(templates)} kanji -> {OUT.name} ({OUT.stat().st_size // 1024} KB)")
    if mismatched:
        print(f"{len(mismatched)} with SVG stroke count != index strokeCount, e.g. {mismatched[:5]}")


if __name__ == "__main__":
    main()
